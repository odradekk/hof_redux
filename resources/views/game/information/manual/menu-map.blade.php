<ul class="menu-map">
<li><b>主页(Top)</b>所拥有的角色一览。点击角色进入角色页。</li>
<li><b>城镇(Town)</b>商店、打工、招募、锻造、精炼、拍卖、竞技场等设施，以及广场留言板。</li>
<li><b>冒险</b>探索地下城；也可以进入共享首领和模拟战。</li>
<li><b>角色</b>角色一览、记住出战队伍、招募新的同伴。</li>
<li><b>仓库</b>所持道具一览，没有容量上限。</li>
<li><b>拍卖会所(Auction)</b>玩家之间买卖道具。</li>
<li><b>竞技场(Colosseum)</b>排行榜，登记队伍并挑战。</li>
<li><b>设置(Setting)</b>修改密码、删除账号、战斗记录等偏好设定。</li>
<li><b>游戏说明</b>本手册、教学、游戏资料和更新公告。</li>
</ul>
